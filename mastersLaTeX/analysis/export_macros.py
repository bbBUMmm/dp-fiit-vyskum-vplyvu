"""export_macros.py -- write every volatile number as a LaTeX macro.

Why
---
The thesis claims that no number in it is typed by hand. Checking that claim
after the fact (verify_thesis.py) catches mismatches but does not prevent them:
every time a parameter changes, a dozen numbers in the prose silently go stale
and have to be chased. Adding one variable to the generating model is enough to
shift the random stream and invalidate the lot.

So the numbers are not typed at all. They are emitted here as `\newcommand`s and
the prose references them. A re-run updates the thesis; there is nothing to
forget. The cost is that the LaTeX source reads `\numAKdel` instead of `0,318`,
which is the usual and acceptable price of a reproducible document.

Slovak decimal commas are produced here, so the prose never has to care.

Run:  python export_macros.py   ->  out/thesis_numbers.tex
"""
